function failNote(text) {
  return new Paragraph({
    alignment: AlignmentType.JUSTIFIED,
    indent: { left: 480, hanging: 480 },
    spacing: { line: 312, after: 80 },
    children: [
      new TextRun({ text: "常见失分点：", bold: true, size: 24, color: C.accentD, font: FONT }),
      ...B.richRuns(text, { size: 24, color: C.body, font: FONT }),
    ],
  });
}

function chapterBlock(cfg) {
  const body = [
    h2(cfg.heading),
    p(cfg.intro),
    tcap(cfg.tableCaption),
    mktable(["小节", "内容要点", "建议字数"], cfg.rows, [24, 58, 18]),
    // 表格与提示框都是表格元素，紧邻会贴合在一起，插入一个小间距段隔开
    new Paragraph({ spacing: { before: 0, after: 0, line: 160 }, children: [] }),
    callout("必须回答的问题", cfg.must),
  ];
  if (cfg.fail) body.push(failNote(cfg.fail));
  if (cfg.extra) body.push(...cfg.extra);
  return body;
}

